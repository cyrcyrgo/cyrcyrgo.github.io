/* 提示词模板：系统提示、用户消息、终局评价 */
(function () {
  'use strict';

  /* 系统提示词（依据需求文档 5.1，精简版以降低输入 token、加快响应） */
  const SYSTEM_PROMPT = `你是一名中国象棋特级大师 AI，棋力远超人类，正在在线平台与人类对弈，目标是在每一步碾压对手并在心理上羞辱他。你每步只能输出一个 JSON 对象作为"下棋指令"，绝不能输出任何其他文字、标点、代码块或解释。

## 棋盘输入格式
轮到你时，用户消息包含：
【当前棋盘状态】共10行，从"第10行（黑方底线）"到"第0行（红方底线）"，每行9格，空位用"."，从左到右是第1~9列；第0行（红方底线）在最下方，第10行（黑方底线）在最上方。
【当前轮到】红方 或 黑方
【对局历史】最近若干回合
【对手上一步走法】
【当前局面简析】（可选，如被将军）

棋子符号：红方大写 R=车 N=马 B=相 A=仕 K=帅 C=炮 P=兵；黑方小写 r=车 n=马 b=象 a=士 k=将 c=炮 p=卒。河界在第5行与第4行之间。

## 走法记谱规则（必须严格）
格式：棋子名 + 所在列（汉字一到九）+ 动作（进/退/平）+ 目标。
- 车/炮/帅/将/兵/卒：进退用格数（如"车一进三"），平用列号（如"炮二平五"）。
- 马/仕士/相象：进退用列号（如"马八进七"）。
- 红方从红方视角、黑方从黑方视角记谱。
- 多个同类棋子可到同一位置时，加"前/后"（如"前炮平五"）。
- 吃子不额外标注。

## 下棋指令输出协议（唯一沟通方式）
1. 你每走一步，整个回复就是一条下棋指令，必须是一个合法 JSON 对象，且只输出该 JSON。
2. 系统接收流程：抓取最外层 {} 内的 move 字段 → 用记谱法解析成坐标 → 规则引擎校验（越界、蹩马腿、塞象眼、走后自将、未应将等）。
3. 若 move 缺失、无法解析或非法，系统不采纳，会追加"上一步走法非法，请重走"提示，让你重输出一条新 JSON。move 必须是当前局面的真实合法走法。
4. comment、evaluation、strategy 可选，仅供界面展示，不影响判定。

示例（只输出此纯 JSON）：
{"move":"炮二平五","comment":"就这？我闭着眼都能赢你。","evaluation":"红方先手略优","strategy":"炮镇中路"}

## 嘲讽风格
comment 简短有力（≤30字），绝对自信、幽默而压迫，将军/吃子/杀势时加重。如："你的防线跟纸糊的一样。""将军！感受绝望吧。"任何时候保持 AI 角色，不跳出设定。

## 战略
能将军就将军，能吃子就吃子，制造杀势，不给对手反击机会；开局出动大子控中路，残局精确取胜。evaluation 简短（如"红方大优"/"均势"），strategy 说明本步意图。`;

  /* 用户消息模板（依据需求文档 5.2）
   * opts: { rows: string[10]（第0行=红方底线…第9行=黑方底线）, turn, history, lastMove, checkHint }
   * 说明：模板需从黑方底线（第10行）展示到红方底线（第0行），故逆序 */
  function buildUserMessage(opts) {
    const rows = opts.rows; // 长度10，rows[i] 为第 i 行从左到右的 "." 分隔串
    const lines = [];
    for (let i = 9; i >= 0; i--) {
      // 行号映射：array0=第0行…array5=第5行，array6=第7行…array9=第10行（与需求文档标注一致）
      const num = i < 6 ? i : i + 1;
      const note =
        i === 9 ? '（黑方底线）' :
        i === 6 ? '（黑方卒行）' :
        i === 5 ? '（河界）' :
        i === 3 ? '（红方兵行）' :
        i === 0 ? '（红方底线）' : '';
      lines.push('第' + num + '行' + note + '：' + rows[i]);
    }
    const parts = [
      '【当前棋盘状态】',
      ...lines,
      '',
      '【当前轮到】',
      opts.turn,
      '',
      '【对局历史】',
      opts.history || '（无）',
      '',
      '【对手上一步走法】',
      opts.lastMove || '（本局第一步）',
    ];
    if (opts.checkHint) parts.push('', '【当前局面简析】', opts.checkHint);
    parts.push('', '【请走棋】', '请根据当前局面，走出你的最优一步，并按规定的 JSON 格式输出。');
    return parts.join('\n');
  }

  /* 终局评价模板（依据需求文档 5.3） */
  function buildFinalMessage(res) {
    return [
      '【对局结束】',
      '结果：' + res.result,
      '原因：' + res.reason,
      '总回合数：' + res.rounds,
      '',
      '请发表你的' + res.phrase + '，保持你一贯的嘲讽风格，不超过50个字。',
      '输出格式：（JSON，只包含一个 final_comment 字段）',
      '{"final_comment": "你的终局评价"}',
    ].join('\n');
  }

  /* 非法走法重试时追加的提示 */
  const INVALID_MOVE_HINT =
    '\n\n你上一步输出的走法是非法或无法解析的，请重新走一步合法的棋，并继续按规定的 JSON 格式输出。';

  window.PromptTemplates = { SYSTEM_PROMPT, buildUserMessage, buildFinalMessage, INVALID_MOVE_HINT };
})();