# 按不同模板重复多次增加数据量
SEEDS = QA_PAIRS + ROLEPLAYS + TRANSLATES

templates = [
    ("<|user|>{q}\n<|assistant|>{a}\n<|endoftext|>\n"),
    ("问题：{q}\n答：{a}\n<|endoftext|>\n"),
    ("用户：{q}\n助理：{a}\n<|endoftext|>\n"),
    ("Instruction: {q}\nResponse: {a}\n<|endoftext|>\n"),
]

def main(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, "dialog_synthetic.txt")
    with open(out, "w", encoding="utf-8") as f:
        for _ in range(10):
            random.shuffle(SEEDS)
            for q, a in SEEDS:
                tmpl = random.choice(templates)
                f.write(tmpl.format(q=q.strip(), a=a.strip()))
        f.write("<!-- 合成指令数据结束 -->\n")
    print(f"合成对话数据已生成 -> {out}  约 {os.path.getsize(out):,} bytes  {len(SEEDS)*10} 条样本")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/dialog_raw")

